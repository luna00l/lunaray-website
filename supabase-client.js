// If Supabase Auth redirects a Magic Link / OTP callback to the root page with #access_token=... or #error=...,
// forward it automatically to admin.html so the administrator lands directly on the Admin Portal.
(function forwardSupabaseAuthHashToAdmin() {
  try {
    const hash = window.location.hash || '';
    const path = window.location.pathname || '';
    if (
      (hash.includes('access_token=') || hash.includes('error_code=') || hash.includes('error_description=')) &&
      !path.toLowerCase().endsWith('/admin.html') &&
      !path.toLowerCase().endsWith('admin.html')
    ) {
      window.location.replace('admin.html' + hash);
    }
  } catch (_) {}
})();

/**
 * Uploads dropped/selected client footage files to the PRIVATE `project-assets` bucket
 * using Signed Upload URLs generated by the `upload-inquiry-asset` Edge Function,
 * and returns a cryptographically signed 1-click download URL for the `project_inquiries` table.
 *
 * @param {File[]} files
 * @returns {Promise<string[]>}
 */
window.uploadProjectAssetsToSupabase = async function uploadProjectAssetsToSupabase(files) {
  if (!files || !files.length) return [];
  const cfg = window.LUNARAY_SUPABASE_CONFIG;
  const CHUNK_SIZE = 44 * 1024 * 1024; // 44 MB per part (fits under Supabase Free Tier 50 MB per-object limit)
  const MAX_TOTAL_BYTES = 500 * 1024 * 1024; // 500 MB max direct upload limit
  const downloadLinks = [];

  let cumulativeBytes = 0;
  for (const file of files) {
    if (!file || !file.size || file.size <= 0) {
      throw new Error(`"${file?.name || 'File'}" is empty (0 bytes).`);
    }
    cumulativeBytes += file.size;
    if (file.size > MAX_TOTAL_BYTES || cumulativeBytes > MAX_TOTAL_BYTES) {
      throw new Error(`"${file.name}" exceeds the 500 MB direct upload limit. Please use a Google Drive link for projects over 500 MB.`);
    }
  }

  for (const file of files) {
    const mimeType = file.type || 'video/mp4';
    const partCount = Math.max(1, Math.ceil(file.size / CHUNK_SIZE));

    // 1. Request signed upload target(s) + signed download URL from Edge Function
    const prepRes = await fetch(`${cfg.edgeFunctionUrl}?action=prepare-upload`, {
      method: 'POST',
      headers: {
        'apikey': cfg.anonKey,
        'Authorization': `Bearer ${cfg.anonKey}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        fileName: file.name,
        mimeType: mimeType,
        partCount: partCount
      })
    });

    if (!prepRes.ok) {
      throw new Error(`Could not prepare upload for "${file.name}" (HTTP ${prepRes.status}).`);
    }

    const prepData = await prepRes.json();
    const targets = prepData.uploadTargets || [];
    if (targets.length !== partCount) {
      throw new Error(`Mismatched signed upload target count for "${file.name}".`);
    }

    // 2. Upload each part directly to Supabase Storage via its signedUploadUrl
    for (let i = 0; i < partCount; i++) {
      const start = i * CHUNK_SIZE;
      const end = Math.min(start + CHUNK_SIZE, file.size);
      const chunkBlob = partCount === 1 ? file : file.slice(start, end, mimeType);
      const putContentType = partCount === 1 ? mimeType : 'application/octet-stream';

      const uploadRes = await fetch(targets[i].signedUrl, {
        method: 'PUT',
        headers: {
          'Content-Type': putContentType
        },
        body: chunkBlob
      });

      if (!uploadRes.ok) {
        throw new Error(`Uploading "${file.name}" (part ${i + 1}/${partCount}) failed (HTTP ${uploadRes.status}).`);
      }
    }

    downloadLinks.push(prepData.downloadUrl || prepData.storageRef);
  }

  return downloadLinks;
};

/**
 * Validates the inquiry or support payload before sending any network request.
 * @param {Object} payload
 */
window.validateInquiryPayloadClient = function validateInquiryPayloadClient(payload) {
  if (!payload || typeof payload !== 'object') {
    throw new Error('Invalid inquiry submission payload.');
  }
  const fullName = String(payload.full_name || '').trim();
  const email = String(payload.email || '').trim();
  const termsAccepted = payload.terms_accepted === true;
  const isSupportEnquiry =
    payload.record_type === 'support_enquiry' ||
    payload.source === 'contact_support_page';

  if (!fullName) throw new Error('Please enter your full name.');
  if (!email) throw new Error('Please enter your email address.');
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(email)) {
    throw new Error('Please enter a valid email address.');
  }

  if (isSupportEnquiry) {
    const supportTopic = String(payload.support_topic || '').trim();
    const supportMessage = String(payload.support_message || '').trim();
    if (!supportTopic) {
      throw new Error('Please select a support inquiry topic.');
    }
    if (!supportMessage) {
      throw new Error('Please enter your message or support details.');
    }
    if (!termsAccepted) {
      throw new Error('Please agree to the Terms & Conditions.');
    }
    return;
  }

  const projectType = String(payload.project_type || '').trim();
  const targetPlatform = String(payload.target_platform || '').trim();
  const videoCount = Number(payload.video_count);
  const targetDuration = String(payload.target_duration || '').trim();
  const budgetTier = String(payload.budget_tier || '').trim();
  const projectDescription = String(payload.project_description || '').trim();

  if (!['short-form', 'youtube-long', 'anime-amv', 'commercial', 'audio-sound', 'thumbnail-only'].includes(projectType)) {
    throw new Error('Please select a project type.');
  }
  if (!['youtube', 'instagram', 'cross-platform', 'other'].includes(targetPlatform)) {
    throw new Error('Please select a target platform.');
  }
  if (!Number.isInteger(videoCount) || videoCount < 1) {
    throw new Error('Please enter the number of videos (at least 1).');
  }
  if (!targetDuration) {
    throw new Error('Please enter your estimated target duration.');
  }
  if (!['tier-basic', 'tier-standard', 'tier-premium'].includes(budgetTier)) {
    throw new Error('Please select a budget range.');
  }
  if (!projectDescription) {
    throw new Error('Please describe your project and creative vibe.');
  }
  if (!termsAccepted) {
    throw new Error('Please agree to the project scheduling and revision scope terms.');
  }
};

/**
 * Inserts a project inquiry or support enquiry row into the Supabase `public.project_inquiries` table.
 * @param {Object} payload - Validated inquiry fields from `#studio-booking-form` or `#support-contact-form`
 */
window.submitProjectInquiryToSupabase = async function submitProjectInquiryToSupabase(payload) {
  window.validateInquiryPayloadClient(payload);

  const cfg = window.LUNARAY_SUPABASE_CONFIG;

  const insertToEndpoint = async (baseUrl, apiKey) => {
    const response = await fetch(`${baseUrl}/rest/v1/project_inquiries`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'apikey': apiKey,
        'Authorization': `Bearer ${apiKey}`,
        'Prefer': 'return=minimal'
      },
      body: JSON.stringify(payload)
    });

    if (!response.ok) {
      let errDetail = `HTTP ${response.status}`;
      try {
        const errJson = await response.json();
        errDetail = errJson.message || errJson.details || errDetail;
      } catch (_) {}
      throw new Error(errDetail);
    }

    return true;
  };

  await insertToEndpoint(cfg.url, cfg.anonKey);

  if (cfg.mirrorProject && cfg.mirrorProject.url && cfg.mirrorProject.anonKey) {
    insertToEndpoint(cfg.mirrorProject.url, cfg.mirrorProject.anonKey).catch(() => {});
  }

  return true;
};

/**
 * Inserts a Contact Support enquiry row with `record_type = 'support_enquiry'` and no fake project fields.
 * @param {Object} payload
 */
window.submitSupportEnquiryToSupabase = async function submitSupportEnquiryToSupabase(payload) {
  const cleanSupportPayload = {
    full_name: String(payload?.full_name || '').trim(),
    email: String(payload?.email || '').trim(),
    support_topic: String(payload?.support_topic || '').trim(),
    support_message: String(payload?.support_message || '').trim(),
    terms_accepted: payload?.terms_accepted === true,
    record_type: 'support_enquiry',
    source: 'contact_support_page'
  };
  return window.submitProjectInquiryToSupabase(cleanSupportPayload);
};
